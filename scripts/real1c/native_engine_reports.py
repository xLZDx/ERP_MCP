"""Native 1C engine-report generator (evidence class NATIVE_ENGINE_REPORT, NON-validating).

Runs a fixed allowlist of standard 1C reports (data composition schema route) on the 818HA reference clone and
exports each result to a private directory OUTSIDE Git, with a sha256 manifest.

Safety contract (GPT-PM plan erp_mcp-integration-candidate-2026-10-07T09-38-59-875Z-8b11b5):
* The only identity is the dedicated read-only reader ERP_MCP_TEST_READER. Its DPAPI CurrentUser secret is loaded from one
  fixed path. There is no user argument, environment variable or config key and no Admin_1C fallback: nothing in this module
  can name another user, and the admin credential files are not referenced here.
* Before any report runs, the reader must prove PASS_WRITE_DENIED on the disposable probe clone (a rolled-back write
  attempt; only a genuine rights refusal counts, any other error is inconclusive and refuses the run). The reference clone
  never receives a write probe. A read-only AccessRight sweep records the reader's remaining write rights (it keeps some on
  service catalogs and registers) and refuses the run if it may write documents, accounting registers, charts of accounts or
  administer the configuration.
* The reference clone row-count fingerprint is taken as the reader, so it covers only the tables the reader may read
  (coverage is recorded). Before the run the metadata fingerprint and every readable table count must equal the reference
  manifest baseline; after the run the readable fingerprint must be identical. A mismatch makes the outputs void.
* The 1C object model is reached only through the chokepoints ``_get`` / ``_put`` / ``_call`` / ``_new``: a fixed set of
  operation names and COM types. Report names come only from ``ALLOWED_REPORTS``. No generic method invocation exists.
* A report that errors or is empty is recorded as UNAVAILABLE/EMPTY. There is no retry and no elevation.
* NATIVE_ENGINE_REPORT is machine-generated by the same 1C engine a human would use, but no human compared it with a screen:
  it can never satisfy ``scripts/real1c/evidence.py`` (only NATIVE_UI_REPORT counts) and never validates a profile.
"""

