class GeneratorRefused(Exception):
    """A safety gate refused the run before any report was generated."""


class UnallowedOperation(PermissionError):
    """Something tried an operation outside the fixed allowlist."""


@dataclass(frozen=True)
class ReportSpec:
    name: str
    start_params: tuple[str, ...]
    end_params: tuple[str, ...]
    cases: tuple[str, ...]
    note: str


